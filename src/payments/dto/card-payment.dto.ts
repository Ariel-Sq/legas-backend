import { ApiProperty, ApiPropertyOptional } from '@nestjs/swagger';
import { Type } from 'class-transformer';
import {
  IsEmail,
  IsIn,
  IsInt,
  IsNotEmpty,
  IsOptional,
  IsString,
  Max,
  MaxLength,
  Min,
  ValidateNested,
} from 'class-validator';
import { MERCADOPAGO_MAX_INSTALLMENTS } from '../payment-method.config';

/**
 * Optional body for POST /api/payments/card/intent. Mirrors the checkout
 * contact form: the order is created before the card form is rendered so the
 * amount can never be tampered with by the client.
 */
export class CardCheckoutIntentDto {
  @ApiPropertyOptional({ example: 'cliente@example.com' })
  @IsOptional()
  @IsEmail()
  @MaxLength(255)
  customerEmail?: string;

  @ApiPropertyOptional({ example: '+54 9 11 1234-5678' })
  @IsOptional()
  @IsString()
  @MaxLength(40)
  customerPhone?: string;

  @ApiPropertyOptional({ example: '30123456' })
  @IsOptional()
  @IsString()
  @MaxLength(20)
  customerDni?: string;

  @ApiPropertyOptional({ enum: ['delivery', 'pickup'] })
  @IsOptional()
  @IsIn(['delivery', 'pickup'])
  deliveryMethod?: 'delivery' | 'pickup';

  @ApiPropertyOptional({ example: 'Av. Siempre Viva 742, CABA' })
  @IsOptional()
  @IsString()
  @MaxLength(500)
  deliveryAddress?: string;

  @ApiPropertyOptional({
    description:
      'Idempotency key for this checkout attempt. A repeated call with the ' +
      'same key reuses the live order instead of creating another.',
  })
  @IsOptional()
  @IsString()
  @MaxLength(80)
  idempotencyKey?: string;
}

export class CardPayerIdentificationDto {
  @ApiProperty({ example: 'DNI' })
  @IsString()
  @IsNotEmpty()
  @MaxLength(10)
  type: string;

  @ApiProperty({ example: '30123456' })
  @IsString()
  @IsNotEmpty()
  @MaxLength(20)
  number: string;
}

export class CardPayerDto {
  @ApiProperty({ example: 'cliente@example.com' })
  @IsEmail()
  email: string;

  @ApiPropertyOptional({ type: () => CardPayerIdentificationDto })
  @IsOptional()
  @ValidateNested()
  @Type(() => CardPayerIdentificationDto)
  identification?: CardPayerIdentificationDto;

  @ApiPropertyOptional()
  @IsOptional()
  @IsString()
  @MaxLength(60)
  firstName?: string;

  @ApiPropertyOptional()
  @IsOptional()
  @IsString()
  @MaxLength(60)
  lastName?: string;
}

/**
 * Body for POST /api/payments/card/pay: the tokenized card data produced by
 * MercadoPago's Card Payment Brick. Raw card numbers never reach this API.
 */
export class CardPaymentDto {
  @ApiProperty({ description: 'Order created by /payments/card/intent' })
  @IsString()
  @IsNotEmpty()
  orderId: string;

  @ApiProperty({ description: 'Card token generated by the Brick' })
  @IsString()
  @IsNotEmpty()
  token: string;

  @ApiProperty({ example: 'visa' })
  @IsString()
  @IsNotEmpty()
  paymentMethodId: string;

  @ApiProperty({ example: 1 })
  @IsInt()
  @Min(1)
  @Max(MERCADOPAGO_MAX_INSTALLMENTS)
  installments: number;

  @ApiPropertyOptional({ example: '303' })
  @IsOptional()
  @IsString()
  issuerId?: string;

  @ApiProperty({ type: () => CardPayerDto })
  @ValidateNested()
  @Type(() => CardPayerDto)
  payer: CardPayerDto;
}
